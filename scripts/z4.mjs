import { chromium } from 'playwright'
const browser = await chromium.launch()
const context = await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width: 1100, height: 800 } })
const page = await context.newPage()
await page.goto('http://localhost:5174', { waitUntil: 'networkidle' })
await page.evaluate(() => document.querySelector('#pre-posle')?.scrollIntoView())
await page.waitForTimeout(500)
const el = await page.$('#pre-posle .relative.aspect-\\[800\\/460\\]')
await el.screenshot({ path: 'reports/r-preposle-full2.png' })
await browser.close()
